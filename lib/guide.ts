// 비서 AI용 — 가이드 전체를 짧은 글로 (site_guide 도구 결과)
export function guideAsText(): string {
  return GUIDE.map((s) =>
    [
      `■ ${s.title} (${s.group} · 주소 ${s.path} · 가이드 /guide#${s.id}) — ${s.summary} 언제: ${s.when}`,
      ...s.parts.map((p) => `  · ${p.name}: ${p.desc}`),
      ...s.tasks.map((t) => `  ▶ ${t.q} → ${t.a}`),
    ].join('\n')
  ).join('\n')
}

// 화면 주소 → 가이드 항목 (비서 AI가 "지금 보는 화면"을 알 때)
export function guideForPath(path: string): GuideSection | null {
  const p = path.split('?')[0]
  return GUIDE.filter((s) => s.id !== 'basics').find((s) => (s.path === '/' ? p === '/' : p.startsWith(s.path))) ?? null
}
